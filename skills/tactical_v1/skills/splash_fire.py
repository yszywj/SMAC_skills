"""S1 SplashFire: Colossus splash mechanism provider.

The splash geometry (beam length/width, full vs splash damage split) is NOT
calibrated for this environment, so secondary-target effects are reported as
HEURISTIC with amount 0 and influence choice only through an explicit,
clearly-labelled coverage bonus. Nothing here enters a "certain kill" budget.
"""
from typing import Dict, List

from ..context import Context, distance
from ..contracts import CALIBRATED, EffectClaim, HEURISTIC


class SplashFireSkill:
    """Registered specialization. It acts as the mechanism provider that G1
    calls for splash units; it never submits a second action on its own."""
    name = "splash_fire"

    def __init__(self, config: Dict):
        params = config.get("splash_fire", {})
        self.coverage_radius = params.get("coverage_radius", 3.0)   # proxy, not SC2 truth
        self.coverage_weight = params.get("coverage_weight", 0.8)
        self.max_secondary = params.get("max_secondary_targets", 4)

    def propose(self, context: Context, memory, telemetry, ledger=None):
        # Provider-only: candidates for splash units are generated by G1 with
        # specialization_provider="splash_fire". Registered so usage of the
        # mechanism is observable and independently disableable.
        return []

    def coverage(self, context: Context, actor: str, enemy_id: str) -> float:
        """Number of other enemies near the primary target (density proxy)."""
        enemy = context.snapshot.enemies[enemy_id]
        return sum(1 for other_id, other in context.snapshot.enemies.items()
                   if other_id != enemy_id
                   and distance(other.position, enemy.position) <= self.coverage_radius)

    def coverage_bonus(self, context: Context, actor: str, enemy_id: str) -> float:
        return min(self.coverage(context, actor, enemy_id), self.max_secondary) \
            * self.coverage_weight

    def target_value(self, context: Context, actor: str, enemy_id: str) -> float:
        """Lower is better (G1 sorts ascending). Density reduces the value."""
        enemy = context.snapshot.enemies[enemy_id]
        return max(enemy.effective_health - self.coverage_bonus(context, actor, enemy_id), 1.0)

    def impact_claims(self, context: Context, actor: str,
                      enemy_id: str) -> List[EffectClaim]:
        """Primary target: calibrated single-target damage. Secondary targets:
        explicitly heuristic coverage, zero credited amount."""
        window = max(int(context.snapshot.step_mul), 1)
        amount, evidence, confidence = context.expected_damage(actor, enemy_id)
        claims = [EffectClaim("damage", enemy_id, max(amount, 0.0), window,
                              evidence, "splash_primary_single_attack", confidence)]
        enemy = context.snapshot.enemies[enemy_id]
        for other_id, other in sorted(context.snapshot.enemies.items()):
            if other_id == enemy_id:
                continue
            if distance(other.position, enemy.position) <= self.coverage_radius:
                claims.append(EffectClaim(
                    "damage", other_id, 0.0, window, HEURISTIC,
                    "uncalibrated_splash_coverage_proxy; excluded from kill budget",
                    0.3))
        return claims
